// Инструменты MCP — тело: подключение, восприятие, движение, глаза.
import { z } from 'zod'
import type { CallToolResult } from '@modelcontextprotocol/sdk/types.js'
import { render } from '../format.js'
import { fail, type Toolkit } from '../toolkit.js'

function register ({ tool, server, daemon }: Toolkit): void {
  tool('mc_connect', 'Подключить бота к серверу. Возвращается, когда мир вокруг прогружен.', {} as Record<string, any>, 'connect')

  tool('mc_disconnect', 'Выйти с сервера.', { reason: z.string().optional() }, 'disconnect')

  // Дешевле всех остальных и, кроме шапки, выгребает накопившиеся события — то
  // есть это ещё и «проверить почту», когда ждать в mc_wait некогда.
  tool(
    'mc_status',
    'Где я и что со мной: координаты, здоровье, еда, инвентарь, время, кто онлайн. ' +
    'Заодно забирает всё, что накопилось, пока ты думал, — включая непрочитанные сообщения игроков (строки ‼). ' +
    'Ждать человека лучше через mc_wait: он вернётся в ту же секунду, когда напишут, а не когда ты спросишь.',
    {} as Record<string, any>, 'status'
  )

  tool(
    'mc_observe',
    'Осмотреться. По умолчанию честно: видно только то, что видно с места глазами — руду сквозь камень не покажет. ' +
    'fair=false включает режим бога (для отладки).',
    { radius: z.number().min(4).max(64).optional(), fair: z.boolean().optional() },
    'observe'
  )

  // Дёшево и не двигает тело: спрашивать можно посреди любой работы. В status
  // есть только список ников — здесь то, чего там нет: где человек и чем занят.
  tool(
    'mc_players',
    'Кто из людей рядом и где: расстояние, направление своими словами («в 4 блоках позади»), ' +
    'что у человека в руке, вооружён ли, видишь ли ты его на самом деле (canSee) или только знаешь, что он там. ' +
    'Плюс куда он СЕЙЧАС смотрит (gaze: на тебя или на какой блок с координатами) и на что недавно указывал долгим ' +
    'взглядом (pointed: блок и координаты) — это ответ на «вот это», «сюда», «сломай его», «поставь туда»: координаты ' +
    'бери отсюда, а не переспрашивай. hp — его здоровье (видно по метаданным сущности), «ранен» при 8 и ниже. ' +
    'mood — твоё настроение и отношение к каждому (друг/знакомый/недолюбливаю/враг) из того, что было за сессию: подарки, ' +
    'драки, грубость, доброе слово, спам зовом. Говори в тон ему. ' +
    'Тело не двигает и ход интента не тратит. Готовая фраза — в text.',
    { radius: z.number().min(4).max(64).optional() },
    'players'
  )

  tool(
    'mc_say',
    'Сказать. Без to — в общий чат, это видят все. ' +
    'to="Ник" — шёпотом лично этому игроку. Отвечай тем же каналом, которым спросили: строка ‼ говорит, ' +
    'был это общий чат или шёпот. Ответить в общий чат на шёпот — значит показать личное всему серверу.',
    { text: z.string().min(1), to: z.string().optional() },
    'say',
    a => ({ text: a.text, to: a.to })
  )

  tool(
    'mc_goto',
    'Идти к координатам. y можно не указывать — тогда цель «дойти до этой колонки», что надёжнее на неровной местности. ' +
    'Со дна собственной шахты сначала вылезает и только потом планирует маршрут (pathfinder не умеет подниматься по ' +
    'колонке 1×1) — это видно по climbedOut.\n' +
    'Два разных «не дошёл», и различать их надо по статусу. failed — попробовал всё, что мог, и не смог в срок: ' +
    'в тексте число попыток и последняя ошибка (весь перечень наружу не отдаётся). done со строкой stopped — ' +
    'кончилось время: тело остановило себя само и доложило, где осталось (at) и сколько до цели по горизонтали ' +
    '(awayBlocks). Второе НЕ значит «дороги нет» — часто значит «дай времени больше» или «цель за тысячу блоков». ' +
    'Поля arrived в таком ответе нет вовсе: на успешном пути это место, куда дошли, и врать им нельзя.\n' +
    'Возвращается по прибытии, при прерывании (чат игрока, урон) или по сроку. Обрывы глубже 4 блоков не преодолевает.',
    {
      x: z.number(),
      z: z.number(),
      y: z.number().optional(),
      range: z.number().min(0).max(16).optional(),
      timeoutSeconds: z.number().min(5).max(300).optional()
    },
    'goto',
    a => ({ ...a, timeoutSeconds: a.timeoutSeconds ?? 50 })
  )

  tool(
    'mc_follow',
    'Ходить за игроком. Ставит постоянную цель и возвращается сразу — дальше вызывай mc_wait, чтобы слушать события пока идёшь.',
    { player: z.string(), distance: z.number().min(1).max(16).optional() },
    'follow'
  )

  tool(
    'mc_escort',
    'Проводить игрока: идти за ним и СМОТРЕТЬ по дороге. Вызов блокирующий, в отличие от mc_follow: ' +
    'возвращается, когда сопровождение кончилось, и приносит числа — сколько прошли (walked), сколько раз ' +
    'отставали (lagged), максимальный разрыв (maxGap), ближе всего подходили (closest), где встали (at), ' +
    'где игрок (player.at, player.gap).\n' +
    'Чем отличается от mc_follow: mc_follow ставит постоянную цель и возвращается сразу, и эта цель переживает ' +
    'и уход игрока, и его выход с сервера — тело продолжает идти к последнему месту, пока не позовёшь mc_stop. ' +
    'escort убирает цель на ЛЮБОМ выходе, включая таймаут снаружи: после ответа тело стоит.\n' +
    'Останавливается сам и говорит, почему и что делать дальше: игрок вышел с сервера; ушёл дальше 40 блоков ' +
    '(«не догнать», с его последними координатами); между нами лава или обрыв (смотрит по прямой на 8 блоков ' +
    'вперёд, обходить не умеет); в бота вцепился моб; застряли в воде. Причина в stopped, что делать — в note, ' +
    'статус при этом остаётся done. Когда просто вышло forSeconds — это нормальный конец: stopped пустой, ' +
    'итоги в note, позови ещё раз, если надо идти дальше.\n' +
    'Сам НЕ дерётся. Удар моба прекращает сопровождение и приносит threat {mob, dist, at} — бить (mc_fight) ' +
    'или уводить игрока, решаешь ты.\n' +
    'Пока идём, ест сам, когда голоден: автопилот в это время не ест — он стоит в стороне, пока работает ' +
    'намерение. Еды в рюкзаке нет — это не остановка, а строка need в ответе.\n' +
    'Игрока с таким ником на сервере нет или он не прогружен — ответ не «не вижу игрока», а факты: кто сейчас ' +
    'онлайн (onlineNow) и где его видели в последний раз (lastSeen). Регистр ника не важен.\n' +
    'Чат прерывает сопровождение (обычно пишет как раз тот, кого ведёшь): тогда придёт status interrupted ' +
    'БЕЗ отчёта, но тело всё равно стоит.\n' +
    'По умолчанию distance 3, forSeconds 60.',
    {
      player: z.string(),
      distance: z.number().min(1).max(16).optional(),
      forSeconds: z.number().min(5).max(300).optional()
    },
    'escort'
  )

  tool(
    'mc_give',
    'Отдать вещь живому человеку: подойти, повернуться, бросить — а потом ДОЖДАТЬСЯ и проверить по миру.\n' +
    'Проверка настоящая: took=true ставится только по пакету collect от сервера — «этот игрок поднял этот стак». ' +
    'Никакого «я бросил, значит отдал» тут нет. Не долетело — took=false, и в drop лежат координаты стака и ' +
    'сколько до него человеку идти.\n' +
    'Ответ про бросок РАЗДЕЛЬНЫЙ, и это важно для тебя. В СТОРОНУ он прицельный: вещь летит туда, куда смотрит ' +
    'тело — измерено, 7 бросков из 7 с годным угловым разрешением легли в передней четверти. Значит повернуться ' +
    'к человеку это не вежливость, а половина дела. А вот НАСКОЛЬКО далеко улетит, не знает никто: пакет, ' +
    'которым mineflayer бросает предмет, дальности не несёт, и живые броски с одного места дали от 0 до 2.8 ' +
    'блока. Поэтому бот целится, но дистанцию не угадывает: встаёт БЛИЗКО (около 2 блоков — с этой дистанции ' +
    'передача в игре и получилась, с 4 и 5 промахнулась), бросает и ПРОВЕРЯЕТ. Промахнулся — подбирает свой же ' +
    'бросок, двигает дистанцию по тому, куда реально унесло, и пробует снова, до 3 раз. Это не запасной путь, а ' +
    'основной механизм: раз дальностью правит случай, никакая константа её не заменит, и измеренная дальность ' +
    'живёт до конца смены — следующий mc_give начинает уже с факта. Наклон при этом выровнен в горизонт: он ' +
    'ничего не решает, но одной случайной величиной меньше. В attempts видно stoodOff (с какой дистанции ' +
    'бросал), pitch (наклон), flight (на сколько унесло), settled (стак успел лечь или его померили в полёте) и ' +
    'fromPlayer (сколько не долетело до человека) — по этим числам видно, промах это или человек не поднял.\n' +
    'Дальше 20 блоков не отдаёт вообще: вернёт road {walk, walkSeconds} — сколько идти, — и ничего не бросит. ' +
    'Сначала mc_goto, потом mc_give снова.\n' +
    'ГРАНИЦА: не отдаёт последнюю кирку (топор/лопату/меч) своего вида, последний кусок еды и броню, надетую на ' +
    'себя. Это не ошибка, а ответ: в keep — что именно жалко, в note — чем перебить. Перебивается force=true; ' +
    'с force броня ещё и снимается сама.\n' +
    'count по умолчанию 1. Предмет можно назвать по-русски («кирку», «еды», «булыжника») или игровым именем; ' +
    'если своего вида несколько, отдаёт ХУДШИЙ — тем, чем работает, бот не разбрасывается.\n' +
    'Нет такого предмета — в note перечислено, что есть, чтобы было чем ответить человеку.',
    {
      player: z.string(),
      item: z.string(),
      count: z.number().min(1).max(64).optional(),
      force: z.boolean().optional(),
      timeoutSeconds: z.number().min(15).max(180).optional()
    },
    'give'
  )

  tool(
    'mc_take',
    'Подобрать то, что человек бросил на землю рядом. Без item берёт всё, что лежит в радиусе; с item ищет ' +
    'названное — и если его там нет, НЕ берёт чужое, а перечисляет в note, что именно валяется и где.\n' +
    'Отчёт по рюкзаку, а не по намерению: took — разница инвентаря до и после, так что «взял» значит «лежит в ' +
    'рюкзаке». Подбор в игре работает ногами, поэтому по дороге в рюкзак попадает и то, чего не просили: это ' +
    'тоже видно в took.\n' +
    'Рюкзак полон — отдельный честный отказ со счётом занятых слотов и тем, что лежит на земле; ' +
    'разгрузиться mc_stash mode=put или mc_chest_put и позвать снова. ' +
    'Вещи на земле живут 5 минут, поэтому это дело первой очереди, а не «потом».',
    {
      item: z.string().optional(),
      radius: z.number().min(2).max(24).optional(),
      timeoutSeconds: z.number().min(5).max(120).optional()
    },
    'take'
  )

  tool('mc_stop', 'Бросить текущее занятие и встать.', {} as Record<string, any>, 'stop')

  tool(
    'mc_wait',
    'Ничего не делать и слушать. ЭТО ЕДИНСТВЕННЫЙ СПОСОБ ЖДАТЬ ЧЕЛОВЕКА: пока ты не внутри вызова, ' +
    'написанное тебе лежит и никто тебя не разбудит. Возвращается в ту же секунду, когда игрок написал ' +
    '(текст — в строке ‼ наверху ответа), а также на урон, низкое здоровье и смерть. ' +
    'И на ЖЕСТЫ человека рядом (строка «‼ ЖЕСТ»): присел перед тобой пару раз (привет / «эй, сюда»), прыгает на месте ' +
    'глядя на тебя (зовёт внимание), смотрит в упор, машет рукой в тебя, кинул тебе вещь, лёг спать (ночь пропустится, ' +
    'только если ляжешь и ты). Тело на жест уже ответило само — присело в ответ, повернулось, подобрало брошенное; ' +
    'твоё дело — ответить как живой игрок: словом в чат, делом, встречным жестом. «‼ ДРУГА БЬЮТ» — моб бьёт человека ' +
    'рядом; если тело было свободно, оно уже вступилось (бой приедет событием «отбил …»). ' +
    'ЗОВ: «иди сюда», «ко мне», «смотри», «глянь», «зацени» в чате или присед/прыжки издалека, глядя на тебя, — тело, если ' +
    'свободно, само решает по настроению, бежать ли (событие «иду к …: почему» или «не пошёл к …: почему, шанс»), добегает ' +
    'и смотрит туда, куда он показывает («‼ ЖЕСТ — прибежал…; он показывает на X (x,y,z)»). «Стой» — останавливает. ' +
    'Не пошло, а ты решил, что надо, — mc_goto к нему. ' +
    'Если сообщение УЖЕ лежало непрочитанным, вернётся сразу, а не досидит срок. ' +
    'Автопилот в это время работает ВЕСЬ: ест, надевает лучшую броню, кует кирку взамен стёртой, выбирается из ' +
    'воды, откапывается из завала, уходит от врага на низком здоровье — всё это приедет событиями в этом же ' +
    'ответе. Ожидание для него не занятость, в отличие от штрека. Единственное исключение: если ты перед этим ' +
    'позвал mc_follow, тело идёт за человеком, и ковка кирки подождёт — верстак под идущее тело не встаёт. ' +
    'Разговариваешь с игроком или ждёшь его — бери 280: короткие ожидания жгут ходы впустую.',
    // 280, а не 300: session.wait зажат в 1..300 секунд, и это его собственный
    // предел, а не транспортный. Потолок RPC в daemon-client.js стоит выше любого
    // бюджета намерения — специально, чтобы демон успел ответить своим таймаутом
    // с частичным отчётом, а не потерял сообщение целиком.
    { seconds: z.number().min(1).max(280).optional() },
    'wait',
    a => ({ seconds: a.seconds ?? 30 })
  )

  tool('mc_look_at', 'Повернуться и посмотреть на точку.', { x: z.number(), y: z.number(), z: z.number() }, 'look_at')

  // Vision needs its own registration: it returns a picture, not just text.
  server.registerTool('mc_look', {
    description:
      'ПОСМОТРЕТЬ ГЛАЗАМИ — вернуть картинку того, что бот видит от первого лица. ' +
      'Для оценки построек, пейзажа, «что это там вдалеке» и скринов в чат. ' +
      'Кадр 640x360 стоит ~300 токенов и ~0.5с (первый после запуска — ~8с, прогрев рендера). ' +
      'Для навигации и поиска блоков всё равно дешевле mc_observe, а сюда — когда важно именно увидеть. ' +
      'at — точка, на которую сначала повернуться.',
    inputSchema: {
      width: z.number().min(160).max(1280).optional(),
      height: z.number().min(90).max(720).optional(),
      at: z.object({ x: z.number(), y: z.number(), z: z.number() }).optional(),
      fresh: z.boolean().optional()
    }
  }, async (args: any = {} as Record<string, any>) => {
    try {
      const result = await daemon.call('look', args)
      const content: CallToolResult['content'] = [{ type: 'text', text: render('look', result) }]
      if (result.image) {
        content.push({ type: 'image', data: result.image, mimeType: result.mime || 'image/png' })
      } else {
        content.push({ type: 'text', text: 'картинка не пришла' })
      }
      return { content }
    } catch (err) {
      return fail(`mc_look: ${err.message}`)
    }
  })
}

export { register }
