// Инструменты MCP — выживание: поверхность, укрытие, восстановление, сон.
import { z } from 'zod'
import type { Toolkit } from '../toolkit.js'

function register ({ tool }: Toolkit): void {
  tool(
    'mc_surface',
    'preferPillar=true — быстрее выходить из одноразовой шахты столбом: один новый блок породы на уровень. ' +
    'При мобах, воде, лаве, сыпучей породе или отказе постановки возвращается к лестнице. ' +
    'Выбраться наверх из шахты. По умолчанию копает лесенку (по ней потом можно спуститься, и с неё не сбить), столб — ' +
    'только там, где лесенку не прокопать. Блоки лесенка всё-таки тратит: под ступенькой над пустотой кладёт ' +
    'опору и без блоков туда не пойдёт вовсе. Упёрся в лаву или воду над головой — отходит в сторону и лезет ' +
    'оттуда (сколько раз отошёл — в aside).\n' +
    'Кроме кирки останавливается ещё на: здоровье ниже 6, вода под ногами, строить нечем, и на мобе, который ' +
    'его видит — спиной к нему на лестницу он не полезет. Сначала попробует отгородиться сам; что построил и ' +
    'стоит ли стена до сих пор — в walls [{who, kind, at, blocks, standing}]. Заслон (kind «заслон») закрывает линию, ' +
    'но не дорогу: в открытом месте моб его обходит, и тогда stopped скажет «обошёл мой заслон» и назовёт бой ' +
    '(mc_fight target=…) — это не сломанная стена, и пока он рядом, повторный подъём ответит то же. Блоки стены, ' +
    'которая линию не перекрыла (моб выше, ниже или не в её ряду), в walls не попадают, но стоят в мире — они ' +
    'в met[].built {blocks, at}.\n' +
    'Один вызов — один отрезок подъёма: если вернул stopped, позови ещё раз — кроме случая, когда в note сказано, ' +
    'что звать ещё раз бесполезно.\n' +
    'Поднимается до выхода из ямы, а не до открытого неба: над дном собственного колодца небо и так открыто. ' +
    'targetY — нижняя граница, а не цель: вылез наружу (out=true) — подъём закончен, даже если заказанная высота выше.\n' +
    'Следит за киркой и останавливается заранее: pickaxe {left — сколько ударов всего в рюкзаке, leg — сколько нужно ' +
    'на этот пролёт, toTop — сколько до заказанной высоты}. left меньше toTop значит, что до верха кирки не хватит ' +
    'и её надо где-то взять (на глубине каменная кирка делается из cobbled_deepslate, которым и так набит рюкзак).\n' +
    'hand=true — кирки нет и сделать не из чего (ни досок на верстак, ни верстака): лезть, ломая рукой то, что рука ' +
    'ломает (без дропа — нужен проход): камень 7.5 с за блок, глубинный сланец 15 с. Долго — timeoutSeconds 600 и ' +
    'звать ещё раз; наверху дерево, а из него кирка.',
    {
      targetY: z.number().optional(),
      timeoutSeconds: z.number().min(10).max(600).optional(),
      hand: z.boolean().optional(),
      preferPillar: z.boolean().optional()
    },
    'surface'
  )

  tool(
    'mc_shelter',
    'Пересидеть ночь без кровати: выкопать нишу под собой и закрыть за собой потолок. ' +
    'mode=enter — закопаться, mode=exit — выбраться наверх. Это запасной вариант, когда mc_sleep не проходит ' +
    '(светло, рядом мобы, кровати нет). Главное поле ответа — sealed: потолок не закрылся — это ещё не ночлег, ' +
    'мобы залезут, и note скажет, что делать (обычно копнуть ещё на 1 вниз и закрыться оттуда).',
    {
      mode: z.enum(['enter', 'exit']).optional(),
      depth: z.number().min(1).max(3).optional(),
      torch: z.boolean().optional()
    },
    'shelter'
  )

  tool(
    'mc_refuge',
    'Аварийный отход: мало хп, рядом мобы — укрыться, отлечиться и вернуться к делу. Сам оценивает место (десятки мс) ' +
    'и выбирает: коробка у стены (стены рядом — в зачёт: угол, тупик, навес — меньше блоков и быстрее; нужна ≥ ~6–10 блоков ' +
    'и кирка или мягкий блок, чтобы выломаться), нора вниз на 3 с крышкой (не в Аду), замкнутый карман (свой штрек) или ' +
    'бегство (крипер рядом, вода, лава, нечем строить). Ближний моб дойдёт раньше, чем встанут стены, — сперва рывок прочь. ' +
    'Внутри ест и пьёт до сытости, ждёт хп ≥ minHp (16), не дольше maxSeconds (120), латает вскрытое, потом выходит с дальней ' +
    'от мобов стороны. Урон и мало хп его НЕ прерывают — только чат и смерть. Автопилот зовёт то же сам (событие АВАРИЯ, ' +
    'прерванное дело — «прервано: АВАРИЯ»): пока в шапке «занят: refuge», новых дел не давай — жди mc_wait, потом повтори ' +
    'прерванное. Ответ: how (box/hole/pocket/flee), code (OK / CORNERED / NO_BLOCKS / IN_WATER / LAVA / NO_FOOD), hp0→hp, ' +
    'healed, ate, seconds; look — что увидел вокруг, choice — почему так.',
    {
      minHp: z.number().min(6).max(20).optional(),
      maxSeconds: z.number().min(10).max(300).optional(),
      why: z.string().optional()
    },
    'refuge'
  )

  tool(
    'mc_recover',
    'Сходить за своим лутом после смерти. Без аргументов возьмёт последнюю неразобранную смерть из памяти; можно ' +
    'задать x/y/z или index. Умеет спуск: если лут под землёй, прокопает к нему лесенку.\n' +
    'Вещи лежат 5 минут, поэтому дорога считается ДО первого шага и он может честно отказаться, не потратив ход: ' +
    'road {walk, down, walkSeconds, digSeconds, etaSeconds, leftSeconds} — сравни etaSeconds с leftSeconds. ' +
    'До первого шага отказов ровно четыре: время вещей вышло (такую смерть ещё и спишет из памяти, чтобы следующий ' +
    'вызов не ходил туда же); вниз копать, а кирки нет; дорога длиннее, чем вещи пролежат; дорога длиннее ' +
    'timeoutSeconds — тогда дай больше. force=true снимает эти четыре и только их.\n' +
    'Снаряжение проверяется ДО выхода и не отказывает: броню и щит из рюкзака тело надевает, лучшее оружие берёт ' +
    'в руку — по урону в секунду, так что алмазный топор не сменится деревянным мечом. Лесенка вниз режет киркой ' +
    'и берёт её в руку, поэтому у кучи, перед сбором, оружие возвращается в руку ещё раз — и после сбора тоже: шаги ' +
    'к стакам по узкому ходу тоже копают. Если оружия или щита нет ' +
    'вовсе — строка «⚠ снаряжение» с тем, из чего их сделать, и он всё равно идёт: у кучи после смерти обычно ' +
    'стоит тот, кто убил, так что решай до вызова. На явные x/z о смерти не говорит — это просто место.\n' +
    'Здоровье и мобы проверяются НЕ до выхода, а по приходу. Меньше 6 хп на месте — вниз за лутом не полезет, ' +
    'причина в stopped, но ход уже потрачен на дорогу. Моб у кучи ничего не останавливает: что успел — подобрал, ' +
    'а моб приедет в guard {who, dist}, и что с ним делать, решаешь ты.\n' +
    'Пещера на спуске к куче — как в mc_dig_down: до 3 блоков спрыгивает сам, глубже — только с maxFallHp (хп на ' +
    'все прыжки этого вызова, по умолчанию 0). Без него спуск встанет у пещеры, а отказ назовёт цену и этот же ' +
    'вызов с ней («прыгну, если позовёшь mc_recover x=… y=… z=… maxFallHp=1»); этот отказ и есть stopped, ' +
    'arrived=false, и с уступа бот дальше не идёт — ни дорогой, ни за стаками внизу. Поля — в descended.ledge, ' +
    'сделанные прыжки — в descended.drops.\n' +
    'Подбор у кучи кончается сам: каждому стаку один ход, и до стака, к которому не пройти, бот не ходит кругами до ' +
    'таймаута. Чем кончился подбор — в sweep {ended, taken, left, unvisited, stray}. ended «обошёл всё» — каждый стак ' +
    'кучи получил свой ход; «срок» — время вышло, unvisited стаков не обошёл, и в note зов mc_recover к той же куче ' +
    'с timeoutSeconds и дорогой, посчитанной от места, где бот стоит. left [{what, at, why}] — что пробовал и не ' +
    'достал: первые три — с mc_goto в note, остальные — только координатами в left[].at. Такой стак две минуты считается ' +
    'списанным: повторный mc_recover к нему не ходит и отдаёт его в left с why «списан раньше» — к нему только mc_goto. ' +
    'stray — стаки рядом с ботом, которых не было в куче, когда подбор начался (осыпь от копания): за ними он не ' +
    'гоняется, в note mc_goto к ближнему.',
    {
      x: z.number().optional(),
      y: z.number().optional(),
      z: z.number().optional(),
      index: z.number().optional(),
      radius: z.number().min(2).max(24).optional(),
      force: z.boolean().optional(),
      timeoutSeconds: z.number().min(10).max(300).optional(),
      maxFallHp: z.number().min(0).max(20).optional()
    },
    'recover'
  )

  tool(
    'mc_sleep',
    'Ночь целиком, как живой игрок: кровать носим с собой. Можно звать уже в сумерки (с 11840 тиков): поставит ' +
    'кровать и ляжет с первым тиком ночи (12542), раньше, чем вылезут мобы. Сервер (ServerPlayer.startSleepInBed) ' +
    'не даёт лечь, если любой монстр (зомби, скелет, крипер, паук, эндермен, ведьма…; не слизень/фантом) задевает ' +
    'коробку ±8 по x/z и ±5 по высоте вокруг изголовья — СКВОЗЬ стены. Поэтому при мобах рядом тело само уходит ' +
    'в бункер на 6 вниз (засыпает трубу за собой, ниша под кровать): мобы наверху в коробку уже не попадают. ' +
    'Утром свою кровать забирает (take) и вылезает наверх. В Аду и Энде кровать взрывается — откажет. ' +
    'Ответ: sleeping, morning, tookBed, bunker{depth}, log — по шагам; problem=monsters + monsters[] — не вышло ' +
    '(разогнать mc_fight или уйти). othersAwake — ночь не проскочила: не спят другие игроки (встал, не лежит зря). ' +
    'Кровати нет — отказ с рецептом (3 шерсти одного цвета + 3 доски). simple=true — старое «просто лечь рядом». ' +
    'Кровать — ещё и ТОЧКА ВОЗРОЖДЕНИЯ: mode=spawn ставит кровать (или берёт свою рядом) и кликает — в верхнем ' +
    'мире это работает и днём (BedRule can_set_spawn=ALWAYS); кровать остаётся, сломать её — потерять точку. ' +
    'Ставь перед рискованным: у портала в Ад (в Аду кровать взрывается, а смерть там вернёт к порталу), у портала ' +
    'в Энд (смерть в Энде — возрождение рядом, не за тысячу блоков), над спуском за алмазами. mode=take — забрать ' +
    'свою кровать, когда место больше не нужно (точки больше нет). Сон в другой кровати ПЕРЕНОСИТ точку туда. ' +
    'В Энде кровать — оружие по дракону (mc_dragon), не точка.',
    {
      mode: z.enum(['night', 'spawn', 'take']).optional(),
      why: z.string().optional(),
      untilMorning: z.boolean().optional(),
      waitSeconds: z.number().min(5).max(300).optional(),
      take: z.union([z.boolean(), z.literal('auto')]).optional(),
      bunker: z.boolean().optional(),
      exit: z.boolean().optional(),
      invite: z.boolean().optional(),
      timeoutSeconds: z.number().min(60).max(600).optional(),
      simple: z.boolean().optional()
    },
    'sleep')

  tool('mc_wake', 'Встать с кровати.', {} as Record<string, any>, 'wake')
}

export { register }
