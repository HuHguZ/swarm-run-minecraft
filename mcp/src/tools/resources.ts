// Инструменты MCP — добыча и ремесло.
import { z } from 'zod'
import type { Toolkit } from '../toolkit.js'

function register ({ tool }: Toolkit): void {
  tool(
    'mc_mine',
    'Добыть блоки: найти ближайшие видимые блоки, дойти, выкопать нужным инструментом и подобрать выпавшее. ' +
    'Отказывается сразу, если нужного инструмента нет, и в отказе говорит, что именно скрафтить и из чего ' +
    '(отдельно разведены «кирки нет вовсе» и «кирка есть, но не того тира»). ' +
    'block — имя блока, список через запятую, или группа: any_log, any_wood, any_planks, any_sapling, ' +
    'any_leaves, any_ore, stone_like, any_sand. Породу дерева знать заранее не нужно — бери any_log.\n' +
    'ГРАНИЦА ЭТОГО ИНСТРУМЕНТА: ищет только то, что видно ГЛАЗАМИ С ТЕКУЩЕГО МЕСТА. Руда в стене штрека, ' +
    'мимо которой бот прошёл десять минут назад, отсюда не видна, и ответ «не вижу в радиусе N» тут значит ' +
    'именно «не вижу отсюда», а НЕ «её там нет». За такой рудой — mc_mine_seen с координатами из ores. ' +
    'at:{x,y,z} выбирает ровно один названный видимый блок (count тогда 1); при отказе соседний не ломается. ' +
    'collect:false отключает поход за дропом, например при открытии воздушного кармана под водой.',
    {
      block: z.string(),
      count: z.number().min(1).max(64).optional(),
      radius: z.number().min(4).max(64).optional(),
      fair: z.boolean().optional(),
      at: z.object({ x: z.number().int(), y: z.number().int(), z: z.number().int() }).optional(),
      collect: z.boolean().optional(),
      timeoutSeconds: z.number().min(10).max(600).optional()
    },
    'mine'
  )

  tool(
    'mc_dig_down',
    'Копать вниз. Два режима, и это фактически два разных инструмента под одним именем.\n' +
    'shaft (по умолчанию) — колодец строго вниз: быстро и дёшево, но обратно только через mc_surface. ' +
    'direction и torchEvery тут не действуют, и за остатком кирки этот режим не следит. ' +
    'timeoutSeconds действует; если его не задать, срок считается из depth. Не уложился — статус timeout, ' +
    'но отчёт всё равно придёт: сколько выкопал и что подобрал, будет в нём. ' +
    'Смотрит на два блока под ногами и отказывается идти в лаву и воду. Пещера под ногами: пол в 3 блоках и ближе — ' +
    'спрыгивает сам, глубже — только с maxFallHp. Когда прыжка нет вовсе (лава, дна не видно, дороже здоровья), ' +
    'отказ называет лесенку отсюда: поле stairs — сторона, а если подмостить нечем, mine — сколько блоков добыть mc_mine.\n' +
    'stairs — лесенка: на блок дороже за ступеньку, зато по ней выходят пешком, с неё не упасть, она сама ставит ' +
    'факелы, сама подмащивает дырку под ступенькой — и над открытой пещерой тоже: ставит подпорку в клетку ступеньки, ' +
    'блок под ней, и вырезает подпорку (в ответе bridged, propped, underside). В пещеру глубиной до 3 блоков просто спрыгивает. ' +
    'depth здесь — пройденные уровни, а не взмахи. Останавливается ЗАРАНЕЕ по остатку кирки, держа запас на дорогу ' +
    'назад, и называет числа; в ответе pickaxes: [{name,left}] по каждой кирке отдельно — сумма скрывает, что кирка ' +
    'в руке в одном блоке от поломки. Ещё останавливается на лаве и воде рядом, на бедроке и ниже 6 хп.\n' +
    'maxFallHp (оба режима) — сколько хп ты разрешаешь потратить на прыжки в пещеру за ЭТОТ вызов, всего, а не на ' +
    'каждый прыжок. По умолчанию 0: ни одного платного прыжка. Цена — высота минус 3 (6 блоков = 3 хп, 12 = 9), ' +
    'броня её не снижает. Когда лесенке нечем подмостить, а колодцу некуда встать, отказ называет цену и готовый ' +
    'вызов («прыгну, если позовёшь mc_dig_down mode=stairs direction=east maxFallHp=9»), а поле ledge несёт то же ' +
    'полями: drop (price — не хватило maxFallHp; hurt — после прыжка осталось бы меньше 9 хп, там же healTo и ' +
    'waitSeconds; mob — моб у места приземления, waitSeconds; high — с 15 блоков и выше: не хватит и полных 20 хп, ' +
    'повтора нет; lava, water, hazard, deep — не прыгает вовсе), fall, cost, after, retry — параметры повтора, ' +
    'other — сторона, где опора есть, mine — сколько блоков добыть, если подмостить нечем. Сходит с уступа так, ' +
    'чтобы упасть в ту клетку, по которой посчитана цена. Сделанные прыжки — в drops: [{fell, cost, paid, hp}].\n' +
    'Причина всегда в поле stopped, а статус при этом остаётся done. Для похода на глубину бери лесенку.',
    {
      depth: z.number().min(1).max(128).optional(),
      mode: z.enum(['shaft', 'stairs']).optional(),
      direction: z.enum(['north', 'south', 'east', 'west']).optional(),
      torchEvery: z.number().min(0).max(32).optional(),
      timeoutSeconds: z.number().min(10).max(600).optional(),
      maxFallHp: z.number().min(0).max(20).optional()
    },
    'dig_down'
  )

  tool(
    'mc_explore',
    'Искать что-то, чего не видно с текущего места: бот ходит перебежками и осматривается. ' +
    'Один вызов — один отрезок поиска (по умолчанию до 45с). Если не нашёл, вернёт куда дошёл — просто позови ещё раз, ' +
    'поиск продолжится с нового места. direction: north/south/east/west, иначе разведка по кругу.',
    {
      block: z.string().optional(),
      radius: z.number().min(8).max(64).optional(),
      stepDistance: z.number().min(8).max(120).optional(),
      direction: z.enum(['north', 'south', 'east', 'west']).optional(),
      timeoutSeconds: z.number().min(10).max(280).optional()
    },
    'explore'
  )

  tool(
    'mc_craft',
    'Скрафтить предмет. count — сколько ПРЕДМЕТОВ нужно, а не сколько раз крафтить: «палки, count 4» это 4 палки ' +
    'и 2 доски. В ответе count — сколько вышло (рецепты бывают пачками по 4), asked — сколько просили, если числа ' +
    'разошлись.\n' +
    'Верстак: поставит свой, если нужен, и ЗАБЕРЁТ его обратно — в ответе tableBack:true. Чужой верстак, который ' +
    'бот не ставил, использует и оставит стоять. Если верстак не открылся (болезнь 1.21.11), переставит свежий и ' +
    'повторит — тогда note «верстак пришлось переставить».\n' +
    'Четыре доски держатся на верстак и в крафт не идут: без верстака внизу не собрать каменную кирку. Откажет ' +
    'словами «не трачу последние доски» или сделает меньше и скажет, почему. spendReserve:true снимает запрет, ' +
    'если ты точно знаешь, что верстак не понадобится.\n' +
    'При нехватке ингредиентов назовёт тот вариант рецепта, до которого ближе всего, а не первый попавшийся. ' +
    'Может отказать словами «автопилот сейчас делает инструмент» — это не поломка, повтори через секунду.',
    { item: z.string(), count: z.number().min(1).max(64).optional(), spendReserve: z.boolean().optional() },
    'craft'
  )

  tool('mc_place', 'Поставить блок из инвентаря рядом с собой. Без at — ближайшее подходящее место; ' +
    'at:{x,y,z} — только названная клетка в пределах руки, с видимой гранью опоры. При отказе другое место не выбирается.',
    { block: z.string(), at: z.object({ x: z.number().int(), y: z.number().int(), z: z.number().int() }).optional() }, 'place')

  tool(
    'mc_bucket',
    'Набрать ведро воды (fluid=water, по умолчанию) или лавы из ВИДИМОГО источника в radius (24). Пустое ведро берёт ' +
    'только источник — текущую жидкость луч проходит насквозь (BucketItem: ClipContext.Fluid.SOURCE_ONLY), поэтому ' +
    '«рядом река» не значит «наберу»: нужен неподвижный блок. Сам подходит на дальность руки (4.5). ' +
    'Нужно пустое ведро (bucket — 3 железа на верстаке); нет — need. Уже полное — already:true, ничего не делает. ' +
    'Вода нужна на обсидиан (mc_obsidian), от огня и от падения; лава — оружие и топливо.',
    { fluid: z.enum(['water', 'lava']).optional(), radius: z.number().min(4).max(48).optional() },
    'bucket'
  )

  tool(
    'mc_obsidian',
    'Добыть обсидиан на портал (count, по умолчанию 10 — ровно на раму без углов, см. mc_portal). Сначала ломает видимый ' +
    'готовый обсидиан, потом заливает водой ближнюю видимую лаву-источник: встаёт на край вровень с лавой, выливает воду ' +
    'себе под ноги — вода растекается по поверхности, и каждый источник под ней становится обсидианом (код сервера: ' +
    'вода сверху или сбоку, не снизу), — забирает воду обратно и ломает застывшее. Нужна алмазная или незеритовая ' +
    'кирка (иначе обсидиан ничего не роняет, ~9.4 с на блок) и ведро воды или пустое ведро с водой в 32 блоках. ' +
    'Обсидиан над лавой не ломает (дроп сгорит) и раму горящего портала не трогает — такие пропуски в skipped. ' +
    'Лава обычно в пещерах на y -50..-60 и в озёрах на поверхности; найди её глазами (mc_explore/mc_observe) и подойди. ' +
    'Ответ: got (сколько добыл), have (сколько в рюкзаке), poured (сколько раз лил воду), stopped, need.',
    {
      count: z.number().min(1).max(64).optional(),
      radius: z.number().min(6).max(32).optional(),
      timeoutSeconds: z.number().min(30).max(600).optional()
    },
    'obsidian'
  )

  tool(
    'mc_smelt',
    'Переплавить в печи. item — что нужно НА ВЫХОДЕ (iron_ingot, glass, charcoal, cooked_beef), но понимает и вход ' +
    '(raw_iron). Печь найдёт рядом, поставит из инвентаря или скрафтит из 8 булыжников. Топливо выберет само — ' +
    'уголь вперёд досок, инструменты и кровати не жжёт. Долгая операция: если не успеет, вернёт частичный результат ' +
    'с причиной в stopped, а что осталось лежать в печи — в leftInside (чужое, найденное в печи, — в foundInside).',
    {
      item: z.string(),
      count: z.number().min(1).max(64).optional(),
      fuel: z.string().optional(),
      timeoutSeconds: z.number().min(10).max(600).optional()
    },
    'smelt'
  )

  tool(
    'mc_tunnel',
    'Копать горизонтальный штрек — так ищут руду на глубине. Идёт по одному блоку, перед каждым проверяет колонку ' +
    'и её соседей на лаву и воду и ОТКАЗЫВАЕТСЯ вскрывать карман с лавой. Дыру в полу подмащивает сам, а если мостить ' +
    'нечем — скажет, сколько блоков нужно (need {what,count,have}). Ставит факелы. height меньше 2 округляет вверх: ' +
    'в щель высотой 1 тело не входит. Направление можно не указывать — пойдёт куда смотрит.\n' +
    'Руду записывает в момент вскрытия стены, а в конце отдаёт ores: имя, сколько, координаты ближайшей и два ' +
    'расстояния — fromHere (развернуться и добрать сейчас) и fromMouth (вернуться потом по уже освещённому штреку).\n' +
    'Если рядом моб, который может до бота добраться — дойти за 12 шагов и меньше, выстрелить по прямой видимости ' +
    'или уже вплотную, — штрек НЕ отходит (в штреке от ближнего боя не отходят), а закладывается блоком и ' +
    'докладывает threat {mob, where, dist, how, steps, drift, wall, placed, sealed}; how — вплотную, дойдёт (steps — ' +
    'за сколько шагов), стреляет, долетит, сквозь стены или не просчитал (путь не посчитать, а бота он видит). ' +
    'Моб, которому не пройти (в пещере под полом, в замурованном кармане сбоку, за рвом — даже если бота видит), не ' +
    'причина вставать: штрек идёт дальше и называет ближайшего такого в behindRock {mob, dist, at, where, why, seen — ' +
    'сколько их}. Исключение одно — моб за породой прямо по ходу штрека: следующие удары эту породу и вскроют, поэтому ' +
    'штрек встаёт без стены, threat.inPath=true и rockBetween=true, а note называет свободные направления — зови ' +
    'mc_tunnel с одним из них. sealed=true — проход закрыт, можно думать ' +
    'спокойно. sealed=false — закрыться не вышло, и drift говорит, какая тут земля: штрек 1×2 (подойти он может ' +
    'только в лоб) или открытое место, где обойти есть где. Драться или нет — решаешь ты, через mc_fight. ' +
    'При how=сквозь стены стена не помогает, и note говорит, что делать вместо неё.\n' +
    'Останавливается заранее по остатку кирки. Недоделанный штрек — это всё равно статус done: причина в stopped, ' +
    'сколько осталось пройти — в remaining, брошенный дроп — в leftBehind. Позови ещё раз, продолжит отсюда.\n' +
    'ores переживает этот ответ: координаты каждой вскрытой руды бот кладёт в память (remembered — записал ' +
    'сейчас, oreMemory — помнит всего). Уходить вперёд, не добирая, теперь не значит потерять: за оставленным ' +
    'вернёшься через mc_mine_seen. mc_mine его уже не найдёт — он смотрит глазами, а не в память.',
    {
      direction: z.enum(['north', 'south', 'east', 'west']).optional(),
      length: z.number().min(1).max(128).optional(),
      height: z.number().min(1).max(3).optional(),
      torchEvery: z.number().min(0).max(32).optional(),
      timeoutSeconds: z.number().min(10).max(600).optional()
    },
    'tunnel'
  )

  tool(
    'mc_mine_seen',
    'ДОБЫТЬ ТО, ЧТО БОТ УЖЕ ВИДЕЛ. Не «осмотрись и найди», а «сходи туда, где ты видел руду, и добудь».\n' +
    'РАЗНИЦА С mc_mine, и она принципиальная. mc_mine смотрит ГЛАЗАМИ ОТСЮДА: про руду в сорока блоках позади ' +
    'он честно скажет «не вижу», и это правда про его зрение, а не про мир. Этот инструмент смотрит В ПАМЯТЬ — ' +
    'в список руды, которую бот лично вскрыл штреком или увидел по прямой. Память — это НЕ рентген: координат, ' +
    'которых бот не видел, в ней нет, и вызов с такими координатами будет ОТКАЗАН, даже если руда там реально ' +
    'есть. В отказе сказано, что помню и что делать (копать штрек и на какой глубине).\n' +
    'Без аргументов — просто список памяти (remembered, kinds, spots). Это справка, текущее занятие она не рвёт.\n' +
    'at — координаты из ores отчёта mc_tunnel, точно или ±1 блок. block — имя руды, тогда возьмёт ближайшую ' +
    'помнящуюся. Достаточно чего-то одного.\n' +
    'ЧЕСТНОСТЬ, читай внимательно: «помню» и «вижу» в ответе разведены. Поле помнил {руда, видел, откуда} — ' +
    'это память, и только память. Сам блок бот перечитывает, ТОЛЬКО дойдя до него. Если там уже не руда ' +
    '(обвал, чужой игрок, лава) — ответ status «пусто» и gone {помнил, сейчас}: не «добыл», не падение. ' +
    'Запись при этом вычёркивается, второй раз её не предложат.\n' +
    'Жилу берёт целиком: первый блок вскрывает по памяти, соседние — уже по факту вскрытия, как их видит ' +
    'человек с киркой в руке. count — максимум блоков за вызов (по умолчанию 8).\n' +
    'Дорогу считает и называет: travel {meters, seconds, swings, dugOnTheWay}. По уже прокопанному штреку ' +
    'swings=0 и dugOnTheWay=false — шёл коридором и кирку не тратил. dugOnTheWay=true значит, что коридор ' +
    'где-то перекрыт (обычно своей же перегородкой от моба) и кирка ушла на объезд.\n' +
    'Лаву за жилой проверяет ДО удара и отказывается вскрывать карман; если лава всё же протекла — остановится, ' +
    'назовёт координаты и сколько успел взять.\n' +
    'Моб в 4 блоках бросает добор, только если может до бота добраться (тот же вопрос и те же how, что у ' +
    'mc_tunnel): тогда mob {mob, dist, at, where, how, steps}, и «вплотную» в stopped значит именно контакт. Моб, ' +
    'которому не пройти, — в behindRock, добор идёт.',
    {
      at: z.object({ x: z.number(), y: z.number(), z: z.number() }).optional(),
      block: z.string().optional(),
      count: z.number().min(1).max(64).optional(),
      timeoutSeconds: z.number().min(20).max(600).optional()
    },
    'mine_seen'
  )
}

export { register }
