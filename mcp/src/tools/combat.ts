// Инструменты MCP — бой, лут, мобы, торговля.
import { z } from 'zod'
import type { Toolkit } from '../toolkit.js'

function register ({ tool }: Toolkit): void {
  tool(
    'mc_fight',
    'Драться. Ты выбираешь ЦЕЛЬ и порог отступления, махать будет модуль — попадать в тайминги через мою задержку невозможно. ' +
    'target можно не указывать: возьмёт ближайшего враждебного моба, а если такого не видно — того, кто бил последние ' +
    '20 секунд. Из воды сначала выходит, после победы подбирает дроп.\n' +
    'В speedrun у самостоятельного боя укажи purpose food/resource/defense; resourceGoal задаёт нужный предмет ' +
    'и общее количество в рюкзаке. command — только явный приказ человека. allowRanged:true разрешает потратить ' +
    'стрелы для этого боя, false запрещает; без него действуют правила режима. clearArea — радиус зачистки ' +
    'после победы (в speedrun по умолчанию 0).\n' +
    'ЩИТ. Если щит есть в рюкзаке, бот сам надевает его в левую руку и держит там дальше — в шапке состояния ' +
    'он виден отдельным полем offHand, а не в рюкзаке. shield: ranged (по умолчанию) — поднимать только на ' +
    'сближении со стрелком; always — держать ещё и между ударами в ближнем бою; never — не трогать. ' +
    'Щит гасит только то, что прилетает спереди, и пока он поднят, бот не бьёт, поэтому в ответе есть блок shield: ' +
    'hpPerSecUnder и hpPerSecOpen — урон в секунду, пока блок стоял, против того же, пока он был опущен. ' +
    'Это ГЛАВНЫЙ ответ на «работает ли щит»: считается из хп внутри одного боя. blocked (сколько ударов ' +
    'погашено по звуку с сервера) бывает нулём даже у работающего щита — свидетель ненадёжный, не суди по нему. ' +
    'confirmed (сколько раз сервер подтвердил подъём метаданными; 0 значит, что щита фактически не было — ' +
    'слушают весь бой, так что это не «не дождались»), upSeconds, facingSeconds, secondsPerSwing (норма 0.65). ' +
    'Всё это — цена решения «закрыться»: прочти её, прежде чем просить always.\n' +
    'БРОНЯ. Если до цели больше шести блоков, бот сначала одевается: автопилот во время работы этого не делает, ' +
    'и раньше бой шёл в том, что случайно оказалось надето. Вплотную не переодевается — дерётся в чём есть. ' +
    'В ответе блок armor: put (что надел), defense, seconds (сколько это стоило кликами), либо already, либо ' +
    'skipped с причиной. Одеться не вышло — бой всё равно идёт, причина будет словами.\n' +
    'retreatAtHealth — это не «убежать». В штреке 1×2 против одного ходячего и с оружием в руке бот НЕ отходит: ' +
    'спринт выключен, зомби быстрее, и отход трижды кончался смертью. Он либо запечатывает штрек блоком ' +
    '(mode «запечатал штрек», sealed), либо продолжает бить и пишет причину в stoodGround. ' +
    'Отход остался для открытого места, для стрелков и когда врагов больше одного.\n' +
    'Урон во время боя не прерывает — иначе бой рвался бы на первом ударе.\n' +
    'На людей бот сам не нападает: ни «ближайшим», ни по нику, ни по слову player. Если человека правда надо ' +
    'ударить — только allowPlayer:true, и это должно быть твоим осознанным решением, а не совпадением имени.\n' +
    'PvP. Против человека бой другой (pvp.js): бьёт с края дальности и отходит в перезарядке, стрейфится, ' +
    'бьёт в прыжке ради крита, W-tap ради отбрасывания, уворачивается от стрел, по щиту — топором; сам кидает ' +
    'паутину, лаву (и забирает обратно), поджигает, кидает снежки/яйца навстречу разбегу, стреляет из лука ' +
    'издалека, пьёт/кидает зелья, ест золотые яблоки, держит тотем, уходит жемчугом. Всё это — из того, что ' +
    'есть в рюкзаке. Ответ: swings/landed/crits/sprintHits, tricks {приём: сколько}, healed, hp «было -> стало». ' +
    'Чат человека такой бой не прерывает — строки приедут в событиях.\n' +
    'Если человек бьёт бота сам, автопилот отвечает без тебя (события provoked / retaliating / retaliated) — ' +
    'настраивается mc_temper; в speedrun эта ответная драка отключена.',
    {
      target: z.string().optional(),
      retreatAtHealth: z.number().min(0).max(19).optional(),
      timeoutSeconds: z.number().min(5).max(300).optional(),
      shield: z.enum(['ranged', 'always', 'never']).optional(),
      // Демон советует этот параметр в тексте отказа (combat.js: «зови fight с
      // allowPlayer: true»), а MCP вырезает всё, чего нет в схеме, — совет был
      // неисполним, и мозг пробовал бы его снова и снова.
      allowPlayer: z.boolean().optional(),
      purpose: z.enum(['food', 'resource', 'defense', 'command']).optional(),
      resourceGoal: z.object({ item: z.string(), count: z.number().int().min(1).max(4096) }).optional(),
      allowRanged: z.boolean().optional(),
      clearArea: z.number().min(0).max(64).optional()
    },
    'fight'
  )

  tool(
    'mc_flee',
    'Убежать от мобов с оглядкой на ВСЕХ, кто рядом: у каждого моба свой радиус опасности (крипер, который шипит, ' +
    'важнее всех), направление выбирается из 24 по опасности в точке прибытия, по тому, как близко путь проходит ' +
    'мимо каждого, и видят ли там стрелки; рельеф проверяется (обрыв, лава, стена). Бежит спринтом, пересчитывая ' +
    'путь каждые 0.3 с, от стрел шагает в сторону. Урон не прерывает. Ответ: mode (оторвался / прижали — бежать ' +
    'некуда / бежал до конца срока), from (от кого), ran (сколько пробежал), dodges. cornered:true — бежать некуда, ' +
    'тогда драться (mc_fight) или закапываться (mc_shelter).',
    { timeoutSeconds: z.number().min(3).max(60).optional(), safeDist: z.number().min(6).max(40).optional() },
    'flee'
  )

  tool(
    'mc_loot',
    'Залутать сундук. Без координат — ближайший видимый сундук НА ПОСТРОЙКЕ ИГРЫ (данж: спавнер и замшелый ' +
    'булыжник; шахта: рельсы и паутина, вагонетка с сундуком; храм; деревня; руины портала; крепость; корабль; ' +
    'бастион...) — такие автопилот лутает и сам, когда вокруг тихо (события looting / looted). Чей-то сундук ' +
    '(рядом верстак, печь, кровать или просто непонятно чей, или рядом наша база) бот не трогает — придёт ' +
    'событие loot_seen; взять его можно только force:true, и это решение человека, а не твоё: спроси. ' +
    'Ответ: took {предмет: сколько}, guess (что за место). Взятые сундуки запоминаются и второй раз не зовут.',
    { x: z.number().optional(), y: z.number().optional(), z: z.number().optional(), force: z.boolean().optional() },
    'loot'
  )

  tool(
    'mc_assess',
    'Разобрать врагов вокруг, не двигаясь: кто это, что у каждого в руке и какая броня (у мобов бывают мечи, топоры, ' +
    'броня), сколько бьёт по мне с учётом моей брони, за сколько секунд я его убью лучшим своим оружием против его ' +
    'брони, и в каком порядке их снимать, чтобы получить меньше всего (опасные и быстрые — первыми, шипящий крипер ' +
    '— вне очереди). verdict: драться / осторожно / уходить — по ожидаемому урону против моего запаса хп и лечения. ' +
    'mc_fight при зачистке сам бьёт в этом порядке и сам выбирает оружие под броню цели.',
    { radius: z.number().min(4).max(64).optional() },
    'assess'
  )

  tool(
    'mc_animals',
    'Животные и питомцы. mode=tame — приручить ближайшего видимого неприручённого kind: wolf (кость), cat (сырая треска ' +
    'или лосось), parrot (семена), horse/donkey/mule/llama (садится верхом, пока не стерпит). Шанс по коду сервера: ' +
    'волк и кошка — 1/3 за предмет, попугай — 1/10; успех видно по сердечкам (событие сущности 7), неудача — дым (6), ' +
    'так что used/fails — правда, а не догадка. Возьми с запасом: на волка в среднем 3 кости, бывает 8+. ' +
    'mode=breed — покормить пару взрослых kind (cow/sheep/goat — пшеница, pig — морковь/картошка/свёкла, chicken — ' +
    'семена, rabbit — одуванчик/морковь, horse — золотая морковь/яблоко, wolf — мясо (приручённые), cat — рыба); ' +
    'pairs — сколько пар; ждёт детёныша; у пары после этого 5 минут перерыв. ' +
    'mode=sit / stand — усадить своих питомцев рядом или поднять, чтобы шли следом. ' +
    'Приручённый волк дерётся за тебя и за хозяина, кошка отпугивает криперов и фантомов.',
    {
      mode: z.enum(['tame', 'breed', 'sit', 'stand']).optional(),
      kind: z.string().optional(),
      tries: z.number().min(1).max(40).optional(),
      pairs: z.number().min(1).max(8).optional(),
      radius: z.number().min(4).max(48).optional()
    },
    'animals'
  )

  tool(
    'mc_golem',
    'Построить голема рядом. kind=iron — Т из 4 железных блоков (iron_block) и вырезанная тыква сверху; kind=snow — 2 ' +
    'снежных блока (snow_block) и тыква. Тыква: carved_pumpkin или jack_o_lantern, или обычная pumpkin + ножницы — ' +
    'вырежет на месте. Место выбирает само (ровно, 3 в ширину, 3 в высоту), голову ставит последней — так игра ' +
    'проверяет узор. Не хватает — need до всякой стройки. Железный голем защищает от мобов и не трогает тебя; ' +
    'снежный кидает снежки (мобов отвлекает, урона почти нет).',
    { kind: z.enum(['iron', 'snow']).optional() },
    'golem'
  )

  tool(
    'mc_trade',
    'Торговать с ближайшим видимым взрослым жителем. mode=list (по умолчанию) — что продаёт: #index, что отдать (с ' +
    'учётом скидок и спроса — price), что получишь, сколько раз осталось. mode=buy — сделка index (или want=имя ' +
    'предмета — найдёт сама) × times. Не хватает изумрудов/товара — скажет, чего. Безработный житель и ребёнок не ' +
    'торгуют. Изумруды чаще всего добываются продажей жителям: фермер берёт пшеницу/морковь, рыбак — уголь, ' +
    'библиотекарь продаёт книги и чары, оружейник/бронник — железные и алмазные вещи.',
    {
      mode: z.enum(['list', 'buy']).optional(),
      index: z.number().min(0).max(20).optional(),
      want: z.string().optional(),
      times: z.number().min(1).max(64).optional(),
      radius: z.number().min(4).max(48).optional()
    },
    'trade'
  )
}

export { register }
