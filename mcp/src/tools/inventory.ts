// Инструменты MCP — рюкзак, сундуки, база, снаряжение.
import { z } from 'zod'
import type { Toolkit } from '../toolkit.js'

function register ({ tool }: Toolkit): void {
  tool(
    'mc_pack',
    'Рюкзак. mode=status (по умолчанию, ход не тратит): сколько свободных клеток, что хлам, что пойдёт в выброс первым. ' +
    'mode=tidy: выбросить хлам сверх запасов (земля, гравий, гранит, туф, гнилая плоть, семена...) и отойти от него — ' +
    'иначе через 2 секунды тело подберёт всё обратно. Запасы не трогает: булыжник 64, еда 16, факелы 32, доски 16, ' +
    'палки 8; снаряжение (кирки, броня, вёдра, огниво) — никогда. ' +
    'Сам подбор уже думает: если рюкзак полон, а лежит что-то дороже хлама — тело выкинет самое дешёвое и поднимет ' +
    '(событие «выкинул X, чтобы поднять Y»); выкинуть нечего — событие «РЮКЗАК ПОЛОН», и решать тебе: mc_cache или tidy.\n' +
    'also (с tidy): ещё и названное сверх своего числа, целыми стопками — «cobblestone:128, cobbled_deepslate:128». ' +
    'Булыжник не хлам (запас 64), и без also десять его стопок едут в шахту и занимают клетки под руду. Не mc_drop: ' +
    'тот бросает под ноги, и через 2 секунды всё возвращается в рюкзак.',
    { mode: z.enum(['status', 'tidy']).optional(), also: z.string().optional() },
    'pack'
  )

  tool(
    'mc_cache',
    'Схрон: поставить сундук там, где стоишь (найдёт место рядом, сундук возьмёт из рюкзака или сделает из досок), ' +
    'сложить в него лишнее и запомнить под именем «схрон-N» (или name). item — что класть: по умолчанию всё сверх ' +
    'запасов (как mc_stash all), можно список через запятую; keep — «имя:сколько оставить». Это обычная именованная ' +
    'база: вернуться — mc_base mode=go name=схрон-N, забрать — mc_stash mode=take name=схрон-N item=... ' +
    'mode=list — все схроны из памяти с содержимым. Когда ставить: рюкзак полон посреди шахты или похода, а нести всё ' +
    'обратно далеко; перед опасным делом (Ад, крепость, дракон) — оставить ценное, что не нужно в бою.',
    { mode: z.enum(['make', 'list']).optional(), name: z.string().optional(), item: z.string().optional(), keep: z.string().optional() },
    'cache'
  )

  tool(
    'mc_enchant',
    'Зачарование. mode: plan — что есть (стол, полки, лазурит, уровни) и что зачаровать первым с «зачем», без движения; ' +
    'setup — поставить стол (скрафтит из книги + 2 алмазов + 4 обсидиана) и полки кольцом через клетку (15 полок = строка 30, ' +
    'между полкой и столом должен быть воздух); table (по умолчанию) — то же и зачаровать: item — что (иначе сам выберет: меч, ' +
    'лук, ботинки, броня, кирка; дерево/камень/золото не трогает), count — сколько вещей подряд, goal — dragon|nether|mining ' +
    '(меняет порядок). Читает подсказки стола и берёт строку по пользе: острота/добыча на меч, сила/бесконечность на лук, ' +
    'защита и невесомость на броню, эффективность/удача/прочность на кирку; мусор (bane_of_arthropods, knockback, thorns) ' +
    'перебрасывает, зачаровав книгу за 1 уровень. Алмазную вещь на дешёвую строку не тратит, пока верхняя не по карману ' +
    '(now:true — всё равно). anvil — книгу на вещь наковальней (item, book — имя чар; 40+ уровней игра не даст). ' +
    'В ответе enchanted[{item, got, why, cost}], level, lapis, need — чего не хватило.',
    {
      mode: z.enum(['plan', 'setup', 'table', 'anvil']).optional(),
      item: z.string().optional(),
      count: z.number().min(1).max(6).optional(),
      goal: z.enum(['default', 'dragon', 'nether', 'mining']).optional(),
      shelves: z.number().min(0).max(15).optional(),
      book: z.string().optional(),
      now: z.boolean().optional(),
      rerolls: z.number().min(0).max(5).optional()
    },
    'enchant'
  )

  tool(
    'mc_brew',
    'Сварить зелье на варочной стойке. potion: fire_resistance (Ад, лава), strength, healing, regeneration, slow_falling ' +
    '(Энд), swiftness, night_vision… и long_*/strong_* (редстоун продлевает, светопыль усиливает). splash:true — взрывное ' +
    '(+порох). count 1-6 (партии по 3, шаг 20 с). Сам докрафтит порошок из стержня, сливки магмы, сверкающий ломтик, сахар, ' +
    'бутылки из стекла (песок переплавит), стойку (стержень + 3 булыжника), наберёт воды в бутылки у ближайшей воды или из ' +
    'ведра. plan:true — только что нужно и где взять, без движения. Чего не хватило — в missing[{what, count, have, where}].',
    {
      potion: z.string(),
      count: z.number().min(1).max(6).optional(),
      splash: z.boolean().optional(),
      plan: z.boolean().optional()
    },
    'brew'
  )

  tool(
    'mc_kit',
    'Сборы в поход по чек-листу: for = nether | bastion | end (дракон) | stronghold | fight. Считает, что есть, крафтит, что ' +
    'можно сейчас (меч и броня через prep, щит, лук, стрелы, золотые яблоки из слитков и яблока, огниво, ведро, кровати ' +
    'для дракона, золотой шлем для пиглинов — и надевает его), и говорит, чего не хватает и где взять. craft:false — ' +
    'только проверка. ready:false и stopped — не хватает обязательного. Зелья не варит — для них mc_brew. В бою тело само ' +
    'пьёт огнестойкость, когда горит, и ест золотое яблоко на 10 хп и ниже.',
    {
      for: z.enum(['nether', 'bastion', 'end', 'dragon', 'stronghold', 'fight']).optional(),
      craft: z.boolean().optional()
    },
    'kit'
  )

  tool(
    'mc_chest_list',
    'Посмотреть, что лежит в сундуке (или бочке, или эндер-сундуке). Без координат — в ближайшем. ' +
    'В ответе contents плюс slots/used/free.',
    { x: z.number().optional(), y: z.number().optional(), z: z.number().optional() },
    'chest_list'
  )

  tool(
    'mc_chest_put',
    'Положить в сундук. item понимает список через запятую, группы (any_ore, stone_like) и «all». ' +
    'count — сколько предметов всего за вызов. Полный сундук — это обычный ответ, а не ошибка: ' +
    'left — это {имя: причина СЛОВАМИ}, не число («сундук полон, 5 осталось при мне», «перенёс 3 из 10», ' +
    '«нет в инвентаре»); сколько реально легло — в put, свободные слоты сундука — в free.',
    {
      item: z.string(),
      count: z.number().min(1).max(2304).optional(),
      x: z.number().optional(),
      y: z.number().optional(),
      z: z.number().optional()
    },
    'chest_put'
  )

  tool(
    'mc_chest_take',
    'Забрать из сундука. item понимает список, группы и «all» — «all» означает весь сундук. ' +
    'left — {имя: причина словами}, в том числе «инвентарь полон, N осталось в сундуке»; сколько взял — ' +
    'в took, остаток сундука — в contents. free тут про слоты СУНДУКА и про полный рюкзак ничего не говорит.',
    {
      item: z.string(),
      count: z.number().min(1).max(2304).optional(),
      x: z.number().optional(),
      y: z.number().optional(),
      z: z.number().optional()
    },
    'chest_take'
  )

  tool(
    'mc_base',
    'База: где дом. Без параметров — отвечает координатами и НЕ двигает тело (это дёшево, спрашивай смело). ' +
    'mode=set — назначить базу: выберет место в radius (по умолчанию 10) от того, где стою — ровная площадка ' +
    '3x3, без лавы в четырёх блоках, не на сыпучей земле, по возможности под открытым небом; поставит сундук ' +
    '(свой или скрафтит из 8 досок) и факел, если факел есть. Координаты лягут в memory/state.json и ' +
    'переживут перезапуск демона. ЕСЛИ БАЗА УЖЕ ЕСТЬ, set её НЕ ПЕРЕНОСИТ: вернёт already=true и старые ' +
    'координаты — лишний вызов из шахты не должен терять общак. Перенос только move=true, и тогда старые ' +
    'сундуки остаются на старом месте и из памяти уходят. x,y,z — поставить базу в указанной точке вместо ' +
    'выбора (в непрогруженном чанке откажется). mode=go — дойти; arrived=false значит «не успел за ' +
    'timeoutSeconds, позови ещё раз», сломанные по дороге сундуки приедут в lost. mode=forget — забыть. ' +
    'name — если баз несколько. База — это запись в памяти, а не постройка: сундук ставится один раз, ' +
    'дальше через mc_stash.',
    {
      mode: z.enum(['where', 'set', 'go', 'forget']).optional(),
      name: z.string().optional(),
      x: z.number().optional(),
      y: z.number().optional(),
      z: z.number().optional(),
      radius: z.number().min(1).max(64).optional(),
      move: z.boolean().optional(),
      torch: z.boolean().optional(),
      range: z.number().min(1).max(16).optional(),
      timeoutSeconds: z.number().min(5).max(600).optional()
    },
    'base'
  )

  tool(
    'mc_stash',
    'Общак на базе: тот же сундук, но по имени «дом», а не по координатам. Без параметров — что там лежит ' +
    'ПО ПАМЯТИ, мгновенно и не сходя с места (кэш пишут сами открытия сундука). mode=check — дойти и ' +
    'пересчитать глазами, когда память старая или кто-то там был.\n' +
    'mode=put без item — сложить ЛИШНЕЕ. При себе бот оставит сам: инструмент, броню, щит, ведро (и пустое ' +
    'тоже), огниво/часы/компас/карту — целиком; кровать 1; еды по 16 каждого вида; факелов 32; булыжника и ' +
    'дипслейта по 64; досок 16; палок 8; угля и древесного по 16; верстак, печь и сундук по одному. Что ' +
    'осталось при боте — в поле kept, что уехало — в put.\n' +
    'item=all значит ровно то же: «всё» — это вся ДОБЫЧА, резервы держатся. А вот ЯВНЫЙ СПИСОК РЕЗЕРВ ' +
    'СНИМАЕТ: item="cobblestone,coal" или группа item="any_ore" отдаёт названное целиком — это и есть ' +
    'способ сказать «я знаю, что делаю». Смешивать можно: item="all,cobblestone" — лишнее по правилам плюс ' +
    'весь булыжник. keep перебивает и то и другое: строка «имя:число» через запятую (keep="cooked_beef:4, ' +
    'torch:0"), голое имя без числа значит «не отдавать вовсе».\n' +
    'mode=take — забрать; item понимает список, группы и «all» (весь общак). count в put и take — бюджет на ' +
    'ВЕСЬ вызов, а не на каждое имя.\n' +
    'Дальше 48 блоков put/take/check не идут: ответят went=false и «сначала base mode=go, потом сюда» — ' +
    'дорога домой это отдельный ход. Полный сундук и полный рюкзак — тоже нормальные ответы с числами ' +
    '(leftOnMe / left), а не ошибки. Если надо вывалить в сундук вообще всё, включая кирку, — это ' +
    'mc_chest_put item=all по координатам сундука: там резервов нет.',
    {
      mode: z.enum(['list', 'put', 'take', 'check']).optional(),
      name: z.string().optional(),
      item: z.string().optional(),
      count: z.number().min(1).max(2304).optional(),
      // Строка «имя:число», а не число: parseKeep (containers.js) разбирает
      // «cooked_beef:4, torch:0». С z.number() параметр не работал НИ ПРИ КАКОМ
      // значении — 5 превращалось в резерв несуществующему предмету '5', а 0
      // отсекался как falsy и исчезал вовсе.
      keep: z.string().optional()
    },
    'stash'
  )

  tool(
    'mc_armor',
    'Надеть лучшую броню из инвентаря, а щит — в левую руку. Автопилот делает это и сам раз в 15 секунд, когда ' +
    'ничем не занят, а долгие работы — на пороге, строкой «▸ перед выходом». Сюда стоит лезть, если нужно прямо ' +
    'сейчас, перед дракой, или если в ответе было «⚠ снаряжение: надеть броню» — причина в той же строке: моб ближе 6 блоков и видит меня (или бьёт), руки были заняты (ем, переодеваюсь, открыто окно) или работу прервали ещё на пороге. ' +
    'В ответе worn (что надето), ' +
    'defense (сумма защиты) и offHand (что в левой руке). Занятую левую руку не трогает — если там уже что-то ' +
    'лежит (тотем, карта), щит останется в рюкзаке. Если бот уже переодевается или у него открыто окно сундука — ' +
    'скажет об этом в stopped и не тронет ничего.',
    {} as Record<string, any>, 'armor'
  )

  tool('mc_equip', 'Взять предмет в руку или надеть (hand/head/torso/legs/feet/off-hand).',
    { item: z.string(), destination: z.enum(['hand', 'head', 'torso', 'legs', 'feet', 'off-hand']).optional() }, 'equip')

  tool(
    'mc_eat',
    'Поесть. Без аргумента выберет лучшую еду из рюкзака (вёдра с рыбой едой не считаются, хотя minecraft-data ' +
    'думает иначе). Полная сытость — это не ошибка, а обычный ответ «сыт, есть не стал». ' +
    'Факт еды проверяется по миру двумя независимыми свидетелями — выросла сытость ИЛИ убыл свой кусок, — ' +
    'поэтому ate:null с нотой «не поел» действительно значит, что бот не поел.',
    { item: z.string().optional() },
    'eat'
  )

  tool('mc_drop', 'Выбросить предмет из инвентаря.', { item: z.string(), count: z.number().min(1).max(64).optional() }, 'drop')
}

export { register }
